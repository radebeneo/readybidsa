"""Private document storage.

Object paths are generated by the server only: "<organisation id>/<tender id>/<document id>.pdf".
Browsers never receive a path to request directly. They get short-lived signed URLs, issued
only after `readybid_core.authz` has checked the caller's organisation membership.
"""

import uuid
from typing import Any, Protocol


def document_storage_path(organisation_id: str, tender_id: str, document_id: str) -> str:
    # Parse as UUIDs so nothing user-controlled can reach the object path.
    parts = [str(uuid.UUID(value)) for value in (organisation_id, tender_id, document_id)]
    return f"{parts[0]}/{parts[1]}/{parts[2]}.pdf"


def evidence_storage_path(organisation_id: str, document_id: str) -> str:
    """Organisation-level evidence: "<organisation id>/evidence/<document id>.pdf"."""
    org, doc = (str(uuid.UUID(value)) for value in (organisation_id, document_id))
    return f"{org}/evidence/{doc}.pdf"


class StorageError(Exception):
    pass


class DocumentStorage(Protocol):
    def upload_pdf(self, path: str, data: bytes) -> None: ...
    def download(self, path: str) -> bytes: ...
    def signed_url(self, path: str, ttl_seconds: int) -> str: ...
    def remove(self, path: str) -> None: ...


class SupabaseStorage:
    def __init__(self, client: Any, bucket: str) -> None:
        self._bucket = client.storage.from_(bucket)

    def upload_pdf(self, path: str, data: bytes) -> None:
        try:
            self._bucket.upload(path, data, {"content-type": "application/pdf", "upsert": "false"})
        except Exception as error:  # noqa: BLE001 - storage3 raises several error types
            raise StorageError(f"Upload failed: {type(error).__name__}") from error

    def download(self, path: str) -> bytes:
        try:
            return bytes(self._bucket.download(path))
        except Exception as error:  # noqa: BLE001
            raise StorageError(f"Download failed: {type(error).__name__}") from error

    def signed_url(self, path: str, ttl_seconds: int) -> str:
        try:
            result = self._bucket.create_signed_url(path, ttl_seconds)
        except Exception as error:  # noqa: BLE001
            raise StorageError(f"Signing failed: {type(error).__name__}") from error
        url = result.get("signedURL") or result.get("signedUrl")
        if not url:
            raise StorageError("Signing returned no URL.")
        return str(url)

    def remove(self, path: str) -> None:
        try:
            self._bucket.remove([path])
        except Exception as error:  # noqa: BLE001
            raise StorageError(f"Remove failed: {type(error).__name__}") from error
